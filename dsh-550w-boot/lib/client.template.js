/* ============================================================================
   dsh-550w-boot — browser half.

   A CLASSIC browser script registered with the web shell's module loader. Not
   an ES module: no import, no export.

   ==========================================================================
   WHY THIS RUNS BEFORE THE APPLICATION APPEARS
   ==========================================================================

   The shell boots in this order (dsh-web-frontend, WebApp.run):

       modules = __ModuleLoader__.create(...)
       prefetchImmediateTier()        <- prefetches rows marked dsh.client.immediately
       runPluginBoot(ctx)             <- activates every enabled plugin, OURS INCLUDED
       mountApp(ctx)                  <- uiRenderer.mount(#root), the first app paint

   Plugin activation therefore happens BEFORE the application mounts, which is
   the whole reason a flash-free boot animation is possible at all: by the time
   #root is painted, the overlay is already in the document and the app is
   hidden behind a guard. `dsh.client.immediately: true` in package.json makes
   the shell prefetch this bundle during that phase instead of on first use.

   ==========================================================================
   WHY AN IFRAME AND NOT INLINE MARKUP
   ==========================================================================

   The animation is a complete standalone document: it styles `html, body`,
   sets `:root` custom properties and declares `overflow:hidden`. Inlined into
   the application's document, that stylesheet would reach the application —
   `html,body{overflow:hidden}` alone would break the shell's own scrolling —
   and the application's stylesheet would reach into the animation.

   An iframe gives both directions for free, keeps the animation's own
   setTimeout/setInterval timeline untouched (its document is an ordinary
   browser document, not this plugin's scope), and confines the animation's
   `position:fixed` wallpaper to its own viewport. Nothing about the source
   HTML has to be rewritten, which is what makes "drop in another HTML file and
   rebuild" actually work.
   ========================================================================== */
window.__ModuleLoader__.load({
  id: 'dsh-550w-boot/client',
  factory: (require) => {
    var module = { exports: {} }
    var exports = module.exports
    Object.defineProperty(exports, Symbol.toStringTag, { value: 'Module' })

    /* ---------------------------------------------------------------- *
     * Generated by build.mjs. ANIMATION is the source HTML file, JSON
     * encoded so that quotes, newlines and backslashes survive.
     * ---------------------------------------------------------------- */
    const ANIMATION = __ANIMATION_JSON__
    const OPTIONS = __OPTIONS_JSON__
    const BUILD = __BUILD_JSON__
    /* ---------------------------------------------------------------- */

    const OVERLAY_ID = 'dsh-550w-boot-overlay'
    const FRAME_ID = 'dsh-550w-boot-frame'
    const CATCHER_ID = 'dsh-550w-boot-catcher'
    const HINT_ID = 'dsh-550w-boot-hint'
    const GUARD_ID = 'dsh-550w-boot-guard'
    const SESSION_FLAG = '__DSH_550W_BOOT_DONE__'

    /* ---------------------------------------------------------------- *
     * Scheduling.
     *
     * Every deadline here is armed twice: once on a requestAnimationFrame
     * chain, once on a plain timer, and the first one to arrive wins.
     *
     * The frame chain is what makes the timing frame-accurate while the window
     * is being painted — the case that matters, because the animation is the
     * only thing on screen and nothing competes for frames.
     *
     * The timer is what keeps a stalled frame loop from becoming a hidden
     * application. rAF does not advance while the window is hidden or fully
     * occluded (Chromium throttles it to nothing), and a compositor that stops
     * producing frames stops it just as completely. Without the timer path,
     * "the animation never finishes" would mean "#root stays hidden forever",
     * which is the one failure this plugin must not have. Timers keep running
     * in a hidden page, throttled to roughly once a second, which is enough to
     * reveal the application late rather than never.
     *
     * The deadline is wall-clock based in both paths, not a count of frames, so
     * a slow first paint cannot stretch the animation. And the timer carries a
     * little slack, so the frame-accurate path wins whenever frames are running
     * at all.
     * ---------------------------------------------------------------- */
    const now = () => {
      try {
        if (typeof performance === 'object' && performance && typeof performance.now === 'function') {
          return performance.now()
        }
      } catch { /* fall through */ }
      return Date.now()
    }

    const after = (ms, fn) => {
      const started = now()
      let rafId = 0
      let timer = 0
      let done = false

      const fire = () => {
        if (done) return
        done = true
        if (rafId) { try { window.cancelAnimationFrame(rafId) } catch { /* nothing to do */ } }
        if (timer) { try { window.clearTimeout(timer) } catch { /* nothing to do */ } }
        fn()
      }

      const step = () => {
        if (done) return
        if (now() - started >= ms) { fire(); return }
        rafId = window.requestAnimationFrame(step)
      }
      rafId = window.requestAnimationFrame(step)

      try {
        timer = window.setTimeout(fire, ms + OPTIONS.timerSlackMs)
      } catch { /* no timer available; the frame chain is then the only path */ }

      /* Idempotent cancel: never runs fn. */
      return () => {
        done = true
        if (rafId) { try { window.cancelAnimationFrame(rafId) } catch { /* nothing to do */ } }
        if (timer) { try { window.clearTimeout(timer) } catch { /* nothing to do */ } }
      }
    }

    /* The guard: hide the application until the animation is done.
     *
     * `visibility:hidden` rather than `display:none` is deliberate. The shell's
     * theme presenter measures the rendered background as its colour authority
     * and the layout frame measures its columns; a display:none subtree has no
     * boxes to measure and would report zeros. A visibility:hidden subtree
     * keeps its layout, so every measurement the application takes while the
     * animation plays returns the same numbers it would have returned without
     * this plugin. */
    const installGuard = () => {
      if (document.getElementById(GUARD_ID)) return
      const style = document.createElement('style')
      style.id = GUARD_ID
      style.textContent = '#root{visibility:hidden !important}'
      const host = document.head || document.documentElement
      if (host) host.appendChild(style)
    }

    const removeGuard = () => {
      const style = document.getElementById(GUARD_ID)
      if (style && style.parentNode) style.parentNode.removeChild(style)
    }

    /* Build the overlay. Returns the handles the lifecycle needs, so nothing
     * has to be looked up again while the animation is running. */
    const buildOverlay = () => {
      const overlay = document.createElement('div')
      overlay.id = OVERLAY_ID
      /* The animation is decorative; a screen reader should hear the app, not
       * this. The iframe carries no accessible name for the same reason. */
      overlay.setAttribute('aria-hidden', 'true')
      overlay.setAttribute('role', 'presentation')

      const os = overlay.style
      os.position = 'fixed'
      os.top = '0'
      os.left = '0'
      os.right = '0'
      os.bottom = '0'
      os.width = '100%'
      os.height = '100%'
      /* Above every application layer. The shell's own overlays (toasts,
       * dialogs, the command palette) sit in the low thousands. */
      os.zIndex = '2147483000'
      os.background = '#050505'
      os.opacity = '1'
      os.transition = 'opacity ' + OPTIONS.fadeMs + 'ms ease'
      os.pointerEvents = 'auto'
      os.overflow = 'hidden'

      const frame = document.createElement('iframe')
      frame.id = FRAME_ID
      frame.setAttribute('title', '')
      frame.setAttribute('tabindex', '-1')
      frame.setAttribute('scrolling', 'no')
      frame.setAttribute('frameborder', '0')
      /* No sandbox attribute: the animation is our own inline document and
       * needs its scripts, and any sandbox token set here would make the frame
       * cross-origin. */
      const fss = frame.style
      fss.position = 'absolute'
      fss.top = '0'
      fss.left = '0'
      fss.width = '100%'
      fss.height = '100%'
      fss.border = '0'
      fss.display = 'block'
      fss.background = '#050505'

      /* srcdoc is the direct route; a data URL is the fallback for an engine
       * without it. Both give the frame a document of its own. */
      if ('srcdoc' in frame) {
        frame.srcdoc = ANIMATION
      } else {
        frame.src = 'data:text/html;charset=utf-8,' + encodeURIComponent(ANIMATION)
      }
      overlay.appendChild(frame)

      /* A transparent catcher above the frame. Without it every click lands in
       * the animation's document — where it would drag a window around
       * instead of skipping the splash. The animation is a splash here, not an
       * application, so owning the pointer is the correct trade. */
      const catcher = document.createElement('div')
      catcher.id = CATCHER_ID
      const css = catcher.style
      css.position = 'absolute'
      css.top = '0'
      css.left = '0'
      css.right = '0'
      css.bottom = '0'
      css.background = 'transparent'
      css.cursor = 'pointer'
      overlay.appendChild(catcher)

      const hint = document.createElement('div')
      hint.id = HINT_ID
      hint.textContent = OPTIONS.hint
      const hs = hint.style
      hs.position = 'absolute'
      hs.right = '16px'
      hs.bottom = '14px'
      hs.color = '#8a5a10'
      hs.font = '12px/1.6 "Microsoft YaHei", "Cascadia Code", Consolas, monospace'
      hs.letterSpacing = '2px'
      hs.opacity = '0'
      hs.transition = 'opacity 600ms ease'
      hs.pointerEvents = 'none'
      overlay.appendChild(hint)

      return { overlay, frame, catcher, hint }
    }

    /* Play once per page load, then get out of the way.
     *
     * Returns a disposer so that unloading the plugin (or an HMR rebuild) takes
     * the overlay and the guard with it. Leaving the guard behind would hide
     * the application with nothing left to reveal it, which is the one failure
     * mode this plugin must not have. */
    const play = (label) => {
      if (window[SESSION_FLAG]) {
        // eslint-disable-next-line no-console
        console.log('[boot550w] v' + BUILD.version + ' already played in this page load; not replaying')
        return () => {}
      }

      installGuard()

      const root = document.body || document.documentElement
      if (!root) throw new Error('no document body to attach the overlay to')

      const { overlay, catcher, hint } = buildOverlay()
      root.appendChild(overlay)

      /* Written only once the overlay is really in the document, so a failure
       * above does not mark the page as "already played". */
      window[SESSION_FLAG] = true

      const started = now()
      let finished = false
      let cancelDeadline = () => {}
      let cancelHint = () => {}

      const cleanup = () => {
        cancelDeadline()
        cancelHint()
        window.removeEventListener('keydown', onKey, true)
        window.removeEventListener('pointerdown', onPointer, true)
        catcher.removeEventListener('click', onPointer)
      }

      const finish = (why) => {
        if (finished) return
        finished = true
        cleanup()

        /* The guard lifts as the fade starts, so the application cross-fades in
         * underneath rather than appearing after a black frame. */
        removeGuard()
        overlay.style.opacity = '0'

        const drop = () => {
          if (overlay.parentNode) overlay.parentNode.removeChild(overlay)
          // eslint-disable-next-line no-console
          console.log('[boot550w] v' + BUILD.version + ' overlay removed after '
            + Math.round(now() - started) + 'ms (' + why + ')')
        }
        after(OPTIONS.fadeMs + 40, drop)
      }

      const onPointer = () => { finish('skipped by pointer') }
      const onKey = (event) => {
        /* Modifier-only presses are not a decision to skip. */
        if (event.key === 'Shift' || event.key === 'Control' || event.key === 'Alt' || event.key === 'Meta') return
        finish('skipped by key ' + JSON.stringify(event.key))
      }

      catcher.addEventListener('click', onPointer)
      window.addEventListener('pointerdown', onPointer, true)
      if (OPTIONS.skipOnAnyKey) window.addEventListener('keydown', onKey, true)

      cancelHint = after(OPTIONS.hintDelayMs, () => { hint.style.opacity = '1' })
      cancelDeadline = after(OPTIONS.durationMs, () => { finish('animation finished') })

      // eslint-disable-next-line no-console
      console.log('[boot550w] v' + BUILD.version + ' overlay mounted from ' + label
        + ' | animation ' + BUILD.animationBytes + ' bytes, duration '
        + OPTIONS.durationMs + 'ms, fade ' + OPTIONS.fadeMs + 'ms')

      return () => {
        cleanup()
        removeGuard()
        if (overlay.parentNode) overlay.parentNode.removeChild(overlay)
      }
    }

    const plugin = {
      name: 'boot550w',
      /* Nothing is injected: this plugin reads no service, and the DOM APIs it
       * uses are not services. cordis refuses a service that was not declared,
       * so an empty inject list is the honest declaration. */
      inject: [],
      apply(ctx) {
        let disposeOverlay = () => {}
        try {
          disposeOverlay = play('plugin activation')
        } catch (error) {
          /* A splash screen is never a reason for the application to fail to
           * start. Reveal the app and say so. */
          removeGuard()
          // eslint-disable-next-line no-console
          console.error('[boot550w] overlay failed, continuing without it', error)
        }

        if (ctx && typeof ctx.effect === 'function') {
          ctx.effect(() => () => {
            try { disposeOverlay() } catch { /* teardown must not throw */ }
          }, 'dsh-550w-boot: overlay')
        }

        /* Console escape hatch: `__dsh550w.skip()` ends the splash, and
         * `__dsh550w.play()` replays it without a restart. */
        try {
          window.__dsh550w = {
            version: BUILD.version,
            options: OPTIONS,
            skip: () => {
              const catcher = document.getElementById(CATCHER_ID)
              if (catcher) catcher.click()
            },
            play: () => {
              delete window[SESSION_FLAG]
              installGuard()
              play('console replay')
            },
            reveal: removeGuard,
          }
        } catch { /* the handle is a convenience, not a contract */ }
      },
    }

    exports.default = plugin
    exports.plugin = plugin
    exports.apply = plugin.apply
    exports.name = plugin.name
    exports.inject = plugin.inject

    return module.exports
  },
})
